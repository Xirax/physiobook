import { sql } from 'drizzle-orm';
import {
  customType,
  pgEnum,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

/**
 * `users` — patients and the single practitioner/admin (SCHEMA.md §2.1).
 *
 * Three of this table's properties are enforced by Postgres rather than by
 * application code, because an invariant a service checks is an invariant two
 * concurrent requests can break:
 *
 *   • case-insensitive email uniqueness — the `citext` column type, so
 *     Alice@x.com and alice@x.com are one account at the database level;
 *   • at most one admin — a partial unique index on `role`;
 *   • a truthful `updated_at` — a trigger, so a row cannot be changed without
 *     it moving (see migrations/0001_users_updated_at_and_admin.sql).
 *
 * The trigger and the seeded admin row live in that hand-written migration:
 * Drizzle's builder emits tables, columns, enums and indexes, and nothing else
 * here pretends otherwise.
 */

/**
 * Postgres' case-insensitive text, from the `citext` extension.
 *
 * Not a first-class Drizzle type, so it is declared here rather than in a shared
 * "types" module — `users.email` is the only column that wants it, and a second
 * caller can lift it out then.
 *
 * The extension itself is created by docker/postgres/init.sql and never by a
 * migration (PROJECT_STRUCTURE.md §5).
 */
const citext = customType<{ data: string; driverData: string }>({
  dataType: () => 'citext',
});

/** `'user' | 'admin'` — the two JWT roles (CLAUDE.md §2). Roles are not hierarchical. */
export const userRole = pgEnum('user_role', ['user', 'admin']);

export const users = pgTable(
  'users',
  {
    // Generated by the database rather than the application: the default is then
    // true for every writer, including a migration and a hand-typed INSERT.
    // `gen_random_uuid()` is built in from Postgres 13 — no pgcrypto needed.
    id: uuid()
      .primaryKey()
      .default(sql`gen_random_uuid()`),

    email: citext().notNull().unique(),

    // NOT NULL with no default: there is no such thing as a user without
    // credentials, and a nullable column would let one exist for a moment.
    passwordHash: text().notNull(),

    role: userRole().notNull().default('user'),

    fullName: text().notNull(),

    // `withTimezone` is the whole point — everything is stored in UTC and
    // rendered in the practice timezone (CLAUDE.md §4).
    createdAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    // The single-admin invariant. SCHEMA.md §2.1 calls this optional on top of
    // app logic; it is not optional here, because "check then insert" is the
    // same race this project refuses to lose anywhere else (CLAUDE.md §4).
    //
    // A partial index leaves ordinary users unconstrained — only the `admin`
    // rows share an index entry, so the second one collides.
    //
    // Dropping this index is the documented first step of going
    // multi-practitioner (SCHEMA.md §8).
    uniqueIndex('users_single_admin_idx')
      .on(table.role)
      .where(sql`${table.role} = 'admin'`),
  ],
);
